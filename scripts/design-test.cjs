const {_electron:electron}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
(async()=>{
  const directory=await fs.mkdtemp(path.join(os.tmpdir(),'quota-design-'));
  const env={...process.env,QUOTA_TEST_DATA:directory};delete env.ELECTRON_RUN_AS_NODE;
  const executablePath=process.env.QUOTA_PACKAGED_EXE;
  const app=await electron.launch({...(executablePath?{executablePath}:{}),args:[...(executablePath?[]:['.']),'--demo','--test-mode'],env});
  try{
    const page=await app.firstWindow();await page.locator('#mini-codex').filter({hasText:'12%'}).waitFor();
    const compactFit=await page.locator('.compact-provider').evaluateAll(nodes=>nodes.every(node=>{
      const outer=node.getBoundingClientRect();
      const logo=node.querySelector('.mini-logo').getBoundingClientRect();
      const info=node.querySelector('.mini-info').getBoundingClientRect();
      return logo.right<=info.left+1&&info.right<=outer.right+1&&logo.top>=outer.top&&info.bottom<=outer.bottom;
    }));
    assert.equal(compactFit,true,'Compact icons and quota text must fit without overlap');
    const bounds=await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].getBounds());
    assert.equal(bounds.width,464);assert.equal(bounds.height,76);
    assert.equal(await page.locator('.compact-name').textContent(),'Quota Pebble');
    assert.equal(await page.locator('.compact-brand').evaluate(el=>{const name=el.querySelector('.compact-name'),version=el.querySelector('#compact-version'),n=name.getBoundingClientRect(),v=version.getBoundingClientRect(),b=el.getBoundingClientRect();return n.bottom<=v.top&&name.scrollWidth<=name.clientWidth&&n.left>=b.left&&n.right<=b.right;}),true,'Name above version must fit the fixed compact brand area');
    assert.equal(await page.evaluate(async()=>{await document.fonts.ready;return document.fonts.check('16px Inter');}),true);
    await page.emulateMedia({reducedMotion:'reduce'});
    const chevronCenter=selector=>page.locator(selector).evaluate(el=>{const r=el.querySelector('svg').getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2};});
    const compactChevron=await chevronCenter('#toggle');
    await page.locator('#toggle').click();
    await page.locator('#collapse').waitFor({state:'visible'});
    await page.evaluate(()=>Promise.all(document.getAnimations().filter(a=>a.effect?.target?.matches?.('.island')).map(a=>a.finished)));
    const expandedChevron=await chevronCenter('#collapse');
    assert.ok(Math.abs(compactChevron.x-expandedChevron.x)<1&&Math.abs(compactChevron.y-expandedChevron.y)<1,JSON.stringify({compactChevron,expandedChevron}));
    assert.equal(await page.locator('.panel-header').evaluate(el=>getComputedStyle(el).webkitAppRegion),'drag','Header background must drag the window');
    assert.equal(await page.locator('.app-title h1').evaluate(el=>getComputedStyle(el).webkitAppRegion),'drag','Title text must drag the window');
    assert.equal(await page.locator('.panel-header .tools').evaluate(el=>getComputedStyle(el).webkitAppRegion),'no-drag','Header controls must remain clickable');
    const fit=await page.locator('.panel-body').evaluate(el=>({visible:el.clientHeight,content:el.scrollHeight}));
    assert.ok(fit.content<=fit.visible+1,`Reference cards must fit without scrolling: ${JSON.stringify(fit)}`);
    assert.equal(await page.locator('.bar').isVisible(),false);
    const addBounds=await page.locator('#add-account-toggle').boundingBox();
    await page.locator('#add-account-toggle').hover();
    assert.equal(await page.locator('#add-account-toggle').evaluate(el=>getComputedStyle(el).textDecorationLine),'none','Add-account hover must look like a button without link underlining');
    assert.deepEqual(await page.locator('#add-account-toggle').boundingBox(),addBounds,'Hover must not move or resize the add-account button');
    const labels=await page.locator('.quota-number').allTextContents();assert.deepEqual(labels,['36%','57%','12%','62%','88%']);
    assert.equal(await page.locator('.card .plan').evaluateAll(nodes=>nodes.every(el=>el.getClientRects().length>0&&el.scrollWidth<=el.clientWidth+1)),true,'All source-provided plans must be visible without clipping');
    const fills=await page.locator('.track').evaluateAll(nodes=>nodes.map(el=>({value:Number(el.getAttribute('aria-valuenow')),fill:el.firstElementChild.getBoundingClientRect().width/el.getBoundingClientRect().width*100})));
    for(const row of fills)assert.ok(Math.abs(row.value-row.fill)<1,'Bar length and numerical percentage must agree');
    const iconStatus=await page.locator('.provider-icon img').evaluateAll(images=>images.every(image=>image.complete&&image.naturalWidth>0));assert.equal(iconStatus,true);
    const headingsFit=await page.locator('.card-heading').evaluateAll(nodes=>nodes.every(node=>{
      const identity=node.querySelector('.provider-identity').getBoundingClientRect();
      const status=node.querySelector('.connection-status').getBoundingClientRect();
      return node.scrollWidth<=node.clientWidth+1;
    }));
    assert.equal(headingsFit,true,'Small cards must keep account identity and connection status separate');
    await fs.mkdir('test-results',{recursive:true});await page.mouse.move(0,0);await page.screenshot({path:'test-results/design-expanded.png'});
    await page.locator('.card.codex .connection-status').click();
    assert.equal(await page.locator('.card.codex .login').isEnabled(),true);
    assert.match(await page.locator('.card.codex .login').textContent(),/切換 Codex 帳號/);
    assert.match(await page.locator('.card.codex .connection-description').textContent(),/不同帳號/);
    await page.locator('.card.codex').screenshot({path:'test-results/design-codex-account.png'});
    await page.locator('.card.codex .close-connection').click();
    const demoLogout=await page.evaluate(()=>window.quota.logout('codex'));
    assert.equal(demoLogout.ok,false,'Demo must never log out real provider accounts');
    assert.equal((await page.evaluate(()=>window.quota.getState())).providers.codex.status,'ready');
    await page.locator('.card.claude .connection-status').click();
    assert.equal(await page.locator('.card.claude .connection-steps li.done').count(),4);
    await page.locator('.card.claude .auth-message.success').waitFor();
    await page.locator('.card.claude').screenshot({path:'test-results/design-connection.png'});
    await page.locator('.card.claude .close-connection').click();await page.locator('#collapse').click();
    await page.screenshot({path:'test-results/design-compact.png'});
    const baseline=await page.evaluate(()=>window.quota.getState());
    const send=state=>app.evaluate(({BrowserWindow},snapshot)=>BrowserWindow.getAllWindows()[0].webContents.send('state',snapshot),state);
    const unsigned=structuredClone(baseline);unsigned.providers.claude.status='signed_out';unsigned.providers.claude.reading=null;unsigned.providers.claude.error='請完成帳號連接';
    await send(unsigned);await page.locator('#mini-claude').filter({hasText:'未連接'}).waitFor();
    for(const locale of ['zh-TW','en','ja','ko']){
      const localized=structuredClone(unsigned);localized.settings.locale=locale;await send(localized);
      const status=await page.locator('#mini-claude').evaluate(el=>{const text=el.getBoundingClientRect(),alert=el.closest('button').querySelector('.mini-alert').getBoundingClientRect();return {font:parseFloat(getComputedStyle(el).fontSize),textRight:text.right,alertLeft:alert.left};});
      assert.ok(status.font<=10,`${locale}: compact status text must stay small`);assert.ok(status.textRight<=status.alertLeft,`${locale}: status text must not overlap alert ${JSON.stringify(status)}`);
    }
    await send(unsigned);
    await page.screenshot({path:'test-results/design-unsigned.png'});
    const stale=structuredClone(baseline);stale.providers.codex.status='stale';stale.providers.codex.error='暫時無法連線';
    await send(stale);await page.locator('#mini-codex').filter({hasText:'更新失敗'}).waitFor();
    assert.equal(await page.locator('#window-codex').textContent(),'12%');
    assert.match(await page.locator('#window-codex').getAttribute('aria-label'),/上次資料/);
    await page.screenshot({path:'test-results/design-stale.png'});
    await page.evaluate(()=>window.quota.expand(true));
    const limited=structuredClone(baseline);limited.expanded=true;limited.providers.claude.status='unavailable';limited.providers.claude.reading=null;
    limited.providers.claude.error='Claude 配額服務限制查詢頻率（HTTP 429）';limited.providers.claude.errorCode='rate_limit';limited.providers.claude.nextPollAt=Date.now()+3600000;
    await send(limited);await page.locator('.card.claude .status-label').filter({hasText:'服務限流'}).waitFor();
    assert.match(await page.locator('.card.claude .empty-message').textContent(),/1 小時.*自動重試/);
    assert.equal(await page.locator('.card.claude .connect-primary').isEnabled(),true);
    assert.equal(await page.locator('.card.claude .connect-primary').textContent(),'查看官方配額 ↗');
    await app.evaluate(({shell})=>{global.__designUsageUrls=[];shell.openExternal=async url=>{global.__designUsageUrls.push(url);};});
    await page.locator('.card.claude .connect-primary').click();
    assert.deepEqual(await app.evaluate(()=>global.__designUsageUrls),['https://claude.ai/settings/usage']);
    assert.notEqual((await page.evaluate(()=>window.quota.getState())).auth.claude?.phase,'web_login');
    const limitFits=await page.locator('.panel-body').evaluate(el=>el.scrollHeight<=el.clientHeight+1);
    assert.equal(limitFits,true,'A cooled-down provider must not push the other live quota cards out of view');
    await page.locator('.card.claude').screenshot({path:'test-results/design-rate-limit.png'});
    await page.locator('.card.claude .connection-status').click();
    assert.equal(await page.locator('.card.claude .login').isVisible(),true);
    assert.equal(await page.locator('.card.claude .login').isEnabled(),true);
    assert.equal(await page.locator('.card.claude .login').textContent(),'查看官方配額 ↗');
    await page.locator('.card.claude .login').click();
    assert.equal(await app.evaluate(()=>global.__designUsageUrls.length),2);
    assert.match(await page.locator('.card.claude .connection-note').textContent(),/重新登入不會解除限流/);
    await page.locator('.card.claude').screenshot({path:'test-results/design-rate-limit-login.png'});
    const report={passed:true,packaged:!!executablePath,checks:['bundled Inter font','reference card values and layout','three cards fit without scrollbar','expanded panel hides compact bar','bars match percentage values','vector icons load','four completed connection stages','connected success banner','explicit signed-out compact state','stale compact state retains labeled old value'],layout:fit};
    await fs.writeFile('test-results/design.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
  }finally{await app.close();await fs.rm(directory,{recursive:true,force:true,maxRetries:5,retryDelay:200});}
})().catch(e=>{console.error(e);process.exitCode=1;});
